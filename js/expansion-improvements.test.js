import assert from 'node:assert/strict';
import { createRuntime } from './test-support/runtime.js';
const {A}=await createRuntime({mapId:'whispering_woods'});
assert.doesNotThrow(()=>A.adminAction('rerolldailies'),'daily admin uses canonical API');
assert.equal(A.G.dailies.activeDailies.length,3);
A.adminAction('completedailies');
const id=A.G.dailies.activeDailies[0].id;
assert.equal(A.claimDaily(id),true);const gold=A.G.player.zeny;
assert.equal(A.claimDaily(id),false);assert.equal(A.G.player.zeny,gold);
assert.equal(A.setZoneDifficulty('whispering_woods','HARD'),true);
assert.equal(A.G.zoneDifficulty.whispering_woods,'hard');
assert.equal(A.enterSubdungeon('missing'),false);
A.G.mastery.zonePoints.whispering_woods=100;
const speed=A.G.player.moveMult;
assert.equal(A.claimMastery('whispering_woods','bronze'),true);
assert.ok(A.G.player.moveMult>speed,'bronze affects movement');
assert.equal(A.claimMastery('whispering_woods','bronze'),false);
const def=A.CONTENT.monsters.find(m=>m.id==='wolf');
for(let i=0;i<20;i++){const m=A.makeMonster(def,200,200);A.killMonster(m);}
assert.equal(A.G.monsters.filter(m=>m.zoneRareId==='fang_the_bloodwolf'&&m.alive).length,1);
const rare=A.G.monsters.find(m=>m.zoneRareId);
A.killMonster(rare);
assert.equal(rare.deadUntil,Infinity,'zone rares never respawn as normal wolves');
const portal=A.G.portals.find(p=>p.toMap==='ww_goblin_cave');
A.G.player.x=portal.x*32+16;A.G.player.y=portal.y*32+16;
assert.equal(A.enterSubdungeon('ww_goblin_cave'),true);
assert.equal(A.exitSubdungeon(),true);
assert.equal(A.G.player.x,portal.x*32+16);
console.log('Expansion integration passed.');
