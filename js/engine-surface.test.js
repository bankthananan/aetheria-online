const calls = [];
const round = v => (typeof v === 'number' ? Math.round(v * 100) / 100 : typeof v === 'string' ? v : typeof v);
const record = name => function (...args) { calls.push(`${name}|${this.fillStyle ?? ''}|${args.map(round).join(',')}`); };
let seed = 42;
Math.random = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 2 ** 32);
const logs = [];
const origLog = console.log;
console.log = (...a) => { logs.push(a.join(' ')); };
const { A, element } = await createRuntime({ ctx2d: { fillRect: record('fillRect'), drawImage: record('drawImage'), fillText: record('fillText') } });
console.log = origLog;
const sha = s => createHash('sha256').update(s).digest('hex').slice(0, 16);

// 1. selfCheck still runs at boot and passes
assert.ok(logs.some(l => l.includes('[selfcheck] OK')), 'selfCheck ran and passed at boot');

// 2. debug surface is unchanged
assert.deepEqual(Object.keys(A).sort(), AWO_KEYS, 'window.__AWO key set unchanged');

// 3. deterministic render fingerprint per map
// (whispering_woods and sunken_ruins include Champion/Elite badges & affix text under seed 42)
const RENDER = {
  town_awakening: { calls: 557, hash: '1556944fc678a798' },
  whispering_woods: { calls: 846, hash: '2cfed3884aa78f15' },
  sunken_ruins: { calls: 509, hash: 'dda5cea2130d8021' },
};
for (const [mapId, want] of Object.entries(RENDER)) {
  seed = 42;
  A.loadMap(mapId);
  A.G.monsters.forEach(m => { m.x = m.y = m.homeX = m.homeY = 2000; });
  A.setCtx(element('game-canvas'));
  calls.length = 0;
  A.render();
  assert.deepEqual({ calls: calls.length, hash: sha(calls.join('\n')) }, want, `${mapId} render fingerprint`);
}

// 4. A* route is unchanged
A.loadMap('whispering_woods');
const TS = 32, sc = Math.floor(A.G.player.x / TS), sr = Math.floor(A.G.player.y / TS);
let route = null, goal = null;
for (let dr = -14; dr <= 14 && !route; dr++) for (let dc = -14; dc <= 14 && !route; dc++) {
  if (Math.max(Math.abs(dc), Math.abs(dr)) < 8) continue;
  const r = A.findPath(sc, sr, sc + dc, sr + dr);
  if (r && r.length > 1) { route = r; goal = [sc + dc, sr + dr]; }
}
assert.deepEqual({ from: [sc, sr], to: goal, steps: route?.length, hash: sha(JSON.stringify(route)) },
  { from: [2, 2], to: [10, 1], steps: 9, hash: '2591ec8fb3540254' }, 'A* route fingerprint');

