import assert from 'node:assert/strict';
import { createInputController } from './input.js';
import { createRuntime } from './test-support/runtime.js';
const actions=[],moves=[];let blocked=false;
const c=createInputController({move:(x,y)=>moves.push([x,y]),action:a=>actions.push(a),blocked:()=>blocked});
c.pointerDown(11,'move',20,20);c.pointerMove(11,60,20);
c.pointerDown(12,'slot:8',200,200);c.pointerUp(12);
assert.deepEqual(actions,['slot:8']);assert.ok(moves.at(-1)[0]>0);
c.pointerDown(13,'move',30,30);c.pointerUp(13);
assert.ok(moves.at(-1)[0]>0,'second thumb cannot steal joystick');
c.pointerUp(11);assert.deepEqual(moves.at(-1),[0,0]);
blocked=true;c.pointerDown(14,'attack',0,0);c.clear();c.clear();
assert.deepEqual(actions,['slot:8']);
c.dispose();blocked=false;c.pointerDown(15,'attack',0,0);
assert.deepEqual(actions,['slot:8']);
console.log('Multi-pointer input passed.');
const {A}=await createRuntime();
A.G.player.hotbar[8]={type:'item',itemId:'minor_potion'};A.G.player.hp=1;
const potions=A.itemQty('minor_potion');
A.dispatchPlayerAction('slot:8');
assert.equal(A.itemQty('minor_potion'),potions-1);
A.pauseGame('test');A.dispatchPlayerAction('parry');
assert.equal(A.G.player.parryUntil||0,0);
A.resumeGameFromPause('test');
